package parser.tokenizer

enum class Type(val regex: String) {
    WHITESPACE("([ \\t\\r])"),
    COMMENT("((#([^\\n]*))|((?s)/\\*.*?\\*/))"),
    IMPORT_KEYWORD("(import)([^A-Za-z0-9_`]{1}|\\z)"),
    FN_KEYWORD("(fn)([^A-Za-z0-9_`]{1}|\\z)"),
    RETURN_KEYWORD("(return)([^A-Za-z0-9_`]{1}|\\z)"),
    IF_KEYWORD("(if)([^A-Za-z0-9_`]{1}|\\z)"),
    ELSE_KEYWORD("(else)([^A-Za-z0-9_`]{1}|\\z)"),
    ELIF_KEYWORD("(elif)([^A-Za-z0-9_`]{1}|\\z)"),
    WHILE_KEYWORD("(while)([^A-Za-z0-9_`]{1}|\\z)"),
    FOR_KEYWORD("(for)([^A-Za-z0-9_`]{1}|\\z)"),
    NOT_IN_KEYWORD("(!in)([^A-Za-z0-9_`]{1}|\\z)"),
    IN_KEYWORD("(in)([^A-Za-z0-9_`]{1}|\\z)"),
    BREAK_KEYWORD("(break)([^A-Za-z0-9_`]{1}|\\z)"),
    CONTINUE_KEYWORD("(continue)([^A-Za-z0-9_`]{1}|\\z)"),
    DEL_KEYWORD("(del)([^A-Za-z0-9_`]{1}|\\z)"),
    VAR_KEYWORD("(var)([^A-Za-z0-9_`]{1}|\\z)"),
    AS_KEYWORD("(as)([^A-Za-z0-9_`]{1}|\\z)"),
    GET_KEYWORD("(get)([^A-Za-z0-9_`]{1}|\\z)"),
    STRUCT_KEYWORD("(struct)([^A-Za-z0-9_`]{1}|\\z)"),
    STATIC_KEYWORD("(static)([^A-Za-z0-9_`]{1}|\\z)"),
    AND("(and)([^A-Za-z0-9_`]{1}|\\z)"),
    OR("(or)([^A-Za-z0-9_`]{1}|\\z)"),
    BOOLEAN("(true|false)([^A-Za-z0-9_`]{1}|\\z)"),
    NULL("(null)([^A-Za-z0-9_`]{1}|\\z)"),
    IDENTIFIER("(`[A-Za-z_][A-Za-z0-9_]*`|[A-Za-z_][A-Za-z0-9_]*)"),
    QUOTE("(\"|')((?:\\\\\\1|(?!\\1).)*)(\\1)"),
    FLOAT("([0-9]*\\.[0-9]+)"),
    DOT_DOT("(\\.{2})"),
    DOT("(\\.)"),
    INTEGER("([0-9]+)"),
    LEFT_CURLY_BRACE("(\\{)"),
    RIGHT_CURLY_BRACE("(\\})"),
    LEFT_PARENTHESIS("(\\()"),
    RIGHT_PARENTHESIS("(\\))"),
    LEFT_SQUARE_BRACE("(\\[)"),
    RIGHT_SQUARE_BRACE("(\\])"),
    COMPARISON_OPERATOR("(==|!=|<=|>=|<|>)"),
    EQUALS("(=)"),
    MINUS_EQUALS("(-=)"),
    PLUS_EQUALS("(\\+=)"),
    COMMA("(,)"),
    SEMICOLON("(;)"),
    NEWLINE("(\\n+)([ \\n\\t\\r]*)"),
    COLON("(:)"),
    BANG("(!)"),
    PLUS_PLUS("(\\+{2})"),
    MINUS_MINUS("(\\-{2})"),
    PLUS("(\\+)"),
    MINUS("(\\-)"),
    ASTERISK("(\\*)"),
    DOUBLE_SLASH("(\\/\\/)"),
    SLASH("(\\/)"),
    CARET("(\\^)"),
    PERCENT("(\\%)"),
    END_OF_FILE("(?!)"),
    ;
}
